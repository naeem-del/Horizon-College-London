-- Horizon College LMS schema for Supabase Postgres.
-- Same tables as the original SQLite version, with these choices:
--   ids are int4 identities (come back as JS numbers), flags stay 0/1 integers,
--   timestamps are timestamptz, date-only fields (due dates, dob) stay 'YYYY-MM-DD' text,
--   millisecond times (sessions, password tokens) are bigint.
-- Row level security is on for every table with no policies: the app connects as the postgres role
-- (which bypasses RLS), while Supabase's public Data API gets nothing.

CREATE TABLE users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  first_name text, last_name text,
  email text NOT NULL,
  password_hash text NOT NULL,
  role text NOT NULL DEFAULT 'student' CHECK (role IN ('student','tutor','admin')),
  phone text, dob text, postcode text, address text, photo text,
  created_at timestamptz NOT NULL DEFAULT now()
);
-- One account per email, ignoring case
CREATE UNIQUE INDEX users_email_lower ON users (lower(email));

CREATE TABLE awarding_bodies (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL, slug text NOT NULL UNIQUE,
  logo text, website text, description text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE courses (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL, slug text NOT NULL UNIQUE,
  awarding_body_id integer REFERENCES awarding_bodies(id) ON DELETE SET NULL,
  level text, qualification_type text, framework text DEFAULT 'RQF',
  duration text, study_mode text, price double precision DEFAULT 0,
  summary text, description text, entry_requirements text, assessment text,
  image text,
  published integer NOT NULL DEFAULT 1,
  featured integer NOT NULL DEFAULT 0,
  -- Modules open one after another: a learner must finish a module before the next one opens
  sequential integer NOT NULL DEFAULT 1,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE modules (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id integer NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  title text NOT NULL, position integer DEFAULT 0
);
CREATE INDEX modules_course ON modules (course_id);

CREATE TABLE lessons (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  module_id integer NOT NULL REFERENCES modules(id) ON DELETE CASCADE,
  title text NOT NULL,
  kind text NOT NULL DEFAULT 'lesson' CHECK (kind IN ('lesson','assignment')),
  content text, video_url text, attachment text, video_file text,
  position integer DEFAULT 0,
  due_date text,
  assign_to text NOT NULL DEFAULT 'all' CHECK (assign_to IN ('all','selected','batches')),
  total_marks double precision,
  -- SCORM package: folder in storage, the page to launch inside it, and '1.2' or '2004'
  scorm_folder text, scorm_launch text, scorm_version text
);
CREATE INDEX lessons_module ON lessons (module_id);

-- Groups of learners on the same course (e.g. a 40-learner intake split into two). The code prefixes every learner
-- number issued in the batch; next_number only ever goes up, so a number is never given out twice.
CREATE TABLE batches (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id integer NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  name text NOT NULL, code text NOT NULL UNIQUE,
  capacity integer, start_date text, end_date text,
  next_number integer NOT NULL DEFAULT 1,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX batches_course ON batches (course_id);

CREATE TABLE enrolments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  course_id integer NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','active','completed','cancelled')),
  -- The batch a learner is in on a course, and the learner number they were given when they joined it
  batch_id integer REFERENCES batches(id) ON DELETE SET NULL,
  learner_number text UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, course_id)
);
CREATE INDEX enrolments_course ON enrolments (course_id);
CREATE INDEX enrolments_batch ON enrolments (batch_id);

CREATE TABLE lesson_progress (
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  lesson_id integer NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
  completed_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, lesson_id)
);
CREATE INDEX lesson_progress_lesson ON lesson_progress (lesson_id);

CREATE TABLE submissions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  lesson_id integer NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
  file text, original_name text, note text,
  status text NOT NULL DEFAULT 'submitted' CHECK (status IN ('submitted','resubmit','accepted')),
  feedback text,
  mark double precision,
  marked_by integer REFERENCES users(id) ON DELETE SET NULL,
  marked_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  reviewed_at timestamptz
);
CREATE INDEX submissions_lesson_user ON submissions (lesson_id, user_id);
CREATE INDEX submissions_user ON submissions (user_id);

CREATE TABLE enquiries (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL, email text, phone text, dob text, postcode text,
  course_id integer REFERENCES courses(id) ON DELETE SET NULL,
  message text,
  status text DEFAULT 'new' CHECK (status IN ('new','contacted','enrolled','closed')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE course_staff (
  course_id integer NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  PRIMARY KEY (course_id, user_id)
);
CREATE INDEX course_staff_user ON course_staff (user_id);

-- Learners an assignment is set for when it isn't set for the whole course, with optional individual deadlines
CREATE TABLE assignment_learners (
  lesson_id integer NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  due_date text,
  PRIMARY KEY (lesson_id, user_id)
);

-- Batches an assignment is set for (lessons.assign_to = 'batches'), each with an optional deadline of its own.
-- Follows batch membership, so a learner who joins the batch later sees the assignment too.
CREATE TABLE assignment_batches (
  lesson_id integer NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
  batch_id integer NOT NULL REFERENCES batches(id) ON DELETE CASCADE,
  due_date text,
  PRIMARY KEY (lesson_id, batch_id)
);

-- Policy documents uploaded by admins; files live in private storage and are only served to logged-in users
CREATE TABLE policies (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL, description text,
  file text NOT NULL, original_name text,
  audience text NOT NULL DEFAULT 'all' CHECK (audience IN ('all','staff','learners')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- What a SCORM package has saved for each learner: the full data model (JSON text) plus a summary for staff
CREATE TABLE scorm_attempts (
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  lesson_id integer NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
  cmi text NOT NULL DEFAULT '{}',
  status text, score double precision, total_time text,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, lesson_id)
);

-- Times are milliseconds since 1970, as written by password-links.js
CREATE TABLE password_tokens (
  token_hash text PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at bigint NOT NULL,
  created_at bigint NOT NULL
);

-- Login sessions (express-session store); expires is milliseconds since 1970
CREATE TABLE sessions (
  sid text PRIMARY KEY,
  sess text NOT NULL,
  expires bigint NOT NULL
);
CREATE INDEX sessions_expires ON sessions (expires);

-- Failed logins per email, shared by every server instance (replaces the in-memory throttle)
CREATE TABLE login_attempts (
  key text PRIMARY KEY,
  count integer NOT NULL DEFAULT 0,
  first_at timestamptz NOT NULL DEFAULT now()
);

-- Keep Supabase's public Data API out of every table
DO $$
DECLARE t text;
BEGIN
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
  END LOOP;
END $$;
