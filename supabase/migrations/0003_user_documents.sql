-- Personal documents a learner or staff member keeps on their profile (ID, certificates, CV, DBS...).
-- Files live in private storage under documents/; only the owner and administrators can open them.
CREATE TABLE user_documents (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind text NOT NULL DEFAULT 'other' CHECK (kind IN ('id','address','qualification','cv','dbs','right_to_work','other')),
  title text,
  file text NOT NULL,
  original_name text,
  -- Who added it: the person themselves, or an administrator on their behalf
  uploaded_by integer REFERENCES users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX user_documents_user ON user_documents (user_id);
ALTER TABLE user_documents ENABLE ROW LEVEL SECURITY;
